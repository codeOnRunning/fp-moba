import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>{const b=document.querySelector('#start-button');return b&&!b.disabled;},{timeout:60000});
const icons=await page.locator('.ability-glyph svg').count();
await page.locator('#start-settings-button').click(); await page.waitForTimeout(400);
const settings={master:await page.locator('#settings-master-volume').inputValue(),sfx:await page.locator('#settings-sfx-volume').inputValue(),music:await page.locator('#settings-music-volume').inputValue(),keyQ:await page.locator('#settings-key-q').inputValue(),keyJump:await page.locator('#settings-key-jump').inputValue()};
await page.screenshot({path:'screenshots/p4-settings.png'});
await page.locator('#settings-close').click(); await page.waitForTimeout(300);
await page.locator('#start-button').click(); await page.waitForTimeout(4000);
await page.evaluate(()=>window.__fpMoba?.damageDummy(150));
await page.evaluate(()=>{const el=document.querySelector('canvas'); if(el) document.exitPointerLock();});
await page.waitForTimeout(500);
const pauseVisible=await page.locator('#pause-screen').isVisible();
const pauseStats=await page.locator('#pause-stats').textContent();
const minimapData=await page.locator('#minimap').evaluate(canvas=>canvas.toDataURL().length);
await page.screenshot({path:'screenshots/p4-pause-stats.png'});
console.log(JSON.stringify({icons,settings,pauseVisible,pauseStats,minimapData,errors},null,2));
await browser.close();
