import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>{const b=document.querySelector('#start-button');return b&&!b.disabled;},{timeout:60000});
await page.locator('#start-settings-button').click(); await page.waitForTimeout(300);
await page.selectOption('#settings-key-jump','KeyC');
await page.locator('#settings-close').click(); await page.waitForTimeout(300);
await page.locator('#start-button').click(); await page.waitForTimeout(4000);
const before=await page.evaluate(()=>window.__fpMoba?.state());
await page.keyboard.press('c'); await page.waitForTimeout(250);
const after=await page.evaluate(()=>window.__fpMoba?.state());
console.log(JSON.stringify({beforeY:before?.player?.[1],afterY:after?.player?.[1],jumpState:after?.player?.[1] > 1.0,errors},null,2));
await browser.close();
