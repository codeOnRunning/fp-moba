import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>{const b=document.querySelector('#start-button');return b&&!b.disabled;},{timeout:60000});
await page.locator('#start-button').click(); await page.waitForTimeout(800);
const s0=await page.evaluate(()=>window.__fpMoba?.state());
await page.evaluate(()=>window.__fpMoba?.damageDummy(1800)); await page.waitForTimeout(900);
const upgradeVisible=await page.locator('#upgrade-screen').isVisible();
const cards=await page.locator('.upgrade-option').count();
const upgradeText=await page.locator('#upgrade-subtitle').textContent();
const firstCard=await page.locator('.upgrade-option').first().textContent();
await page.locator('.upgrade-option').first().click(); await page.waitForTimeout(900);
const s1=await page.evaluate(()=>window.__fpMoba?.state());
await page.evaluate(()=>window.__fpMoba?.damageDummy(3000)); await page.waitForTimeout(900);
const upgradeVisible2=await page.locator('#upgrade-screen').isVisible();
await page.locator('.upgrade-option').first().click(); await page.waitForTimeout(900);
const s2=await page.evaluate(()=>window.__fpMoba?.state());
await page.evaluate(()=>window.__fpMoba?.damageDummy(4000)); await page.waitForTimeout(900);
const victoryVisible=await page.locator('#victory-screen').isVisible();
const summary=await page.locator('#victory-summary').textContent();
console.log(JSON.stringify({s0,upgradeVisible,cards,upgradeText,firstCard,s1,upgradeVisible2,s2,victoryVisible,summary,errors},null,2));
await page.screenshot({path:'screenshots/upgrade-screen.png'});
await browser.close();
