import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:4173/', {waitUntil:'networkidle'});
await page.waitForFunction(()=>{const b=document.querySelector('#start-button');return b&&!b.disabled;},{timeout:60000});
await page.locator('#start-button').click(); await page.waitForTimeout(700);
await page.evaluate(()=>window.__fpMoba?.faceDummy());
const before=await page.evaluate(()=>window.__fpMoba?.state());
await page.keyboard.down('q'); await page.waitForTimeout(800); await page.keyboard.up('q');
await page.waitForTimeout(2200);
const afterQ=await page.evaluate(()=>window.__fpMoba?.state());
await page.keyboard.press('f'); await page.waitForTimeout(300);
const afterW=await page.evaluate(()=>window.__fpMoba?.state());
const posBeforeE=afterW.player;
await page.keyboard.press('e'); await page.waitForTimeout(350);
const afterE=await page.evaluate(()=>window.__fpMoba?.state());
await page.keyboard.press('r'); await page.waitForTimeout(400);
const afterR=await page.evaluate(()=>window.__fpMoba?.state());
await page.screenshot({path:'screenshots/abilities-test.png'});
console.log(JSON.stringify({before,afterQ,afterW,posBeforeE,afterE,afterR,errors},null,2));
await browser.close();
