import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>{const b=document.querySelector('#start-button');return b&&!b.disabled;},{timeout:60000});
await page.selectOption('#difficulty-select','hard');
const meta=await page.locator('#boss-modifier-label').textContent();
await page.locator('#start-button').click(); await page.waitForTimeout(4000);
const startState=await page.evaluate(()=>window.__fpMoba?.state());
await page.evaluate(()=>window.__fpMoba?.damageDummy(1800)); await page.waitForTimeout(500);
await page.locator('.upgrade-option').first().click(); await page.waitForTimeout(2500);
await page.evaluate(()=>window.__fpMoba?.damageDummy(2200)); await page.waitForTimeout(500);
await page.locator('.upgrade-option').first().click(); await page.waitForTimeout(2500);
await page.evaluate(()=>window.__fpMoba?.damageDummy(2400)); await page.waitForTimeout(800);
const victory=await page.locator('#victory-screen').isVisible();
const build=await page.locator('#victory-build').textContent();
const score=await page.locator('#victory-score').textContent();
const summary=await page.locator('#victory-summary').textContent();
const finalState=await page.evaluate(()=>window.__fpMoba?.state());
console.log(JSON.stringify({meta,startState:{difficulty:startState?.difficulty,modifier:startState?.bossModifier},victory,build,score,summary,finalState:{build:finalState?.build,score:finalState?.score},errors},null,2));
await browser.close();
