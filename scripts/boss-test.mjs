import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>{const b=document.querySelector('#start-button');return b&&!b.disabled;},{timeout:60000});
await page.locator('#start-button').click(); await page.waitForTimeout(800);
const start=await page.evaluate(()=>window.__fpMoba?.state());
const targetHp=await page.locator('#target-hp-text').textContent();
await page.evaluate(()=>window.__fpMoba?.damageDummy(900)); await page.waitForTimeout(600);
const phase2=await page.evaluate(()=>window.__fpMoba?.state());
const phaseText=await page.locator('#target-phase').textContent();
await page.evaluate(()=>window.__fpMoba?.damageDummy(1200)); await page.waitForTimeout(700);
const victoryVisible=await page.locator('#victory-screen').isVisible();
const summary=await page.locator('#victory-summary').textContent();
const best=await page.locator('#victory-best').textContent();
const dead=await page.evaluate(()=>window.__fpMoba?.state());
await page.locator('#victory-retry-button').click(); await page.waitForTimeout(800);
const retry=await page.evaluate(()=>window.__fpMoba?.state());
const retryHidden=await page.locator('#victory-screen').isVisible();
console.log(JSON.stringify({start,targetHp,phase2,phaseText,victoryVisible,summary,best,dead,retry,retryHidden,errors},null,2));
await page.screenshot({path:'screenshots/boss-victory.png'});
await browser.close();
