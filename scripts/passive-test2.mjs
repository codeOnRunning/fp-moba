import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>{const b=document.querySelector('#start-button');return b&&!b.disabled;},{timeout:60000});
await page.locator('#start-button').click(); await page.waitForTimeout(700); await page.evaluate(()=>window.__fpMoba?.faceDummy());
for(let i=0;i<3;i++) await page.evaluate(()=>window.__fpMoba?.damageDummy(1));
await page.waitForTimeout(300);
const before=await page.evaluate(()=>window.__fpMoba?.state());
await page.evaluate(()=>{const c=document.querySelector('#game-canvas');c?.dispatchEvent(new MouseEvent('mousedown',{bubbles:true,button:0}));});
await page.waitForTimeout(100);
const afterDown=await page.evaluate(()=>window.__fpMoba?.state());
await page.evaluate(()=>window.dispatchEvent(new MouseEvent('mouseup',{bubbles:true,button:0})));
await page.waitForTimeout(3000);
const after=await page.evaluate(()=>window.__fpMoba?.state());
console.log(JSON.stringify({before,afterDown,after,errors},null,2)); await browser.close();
